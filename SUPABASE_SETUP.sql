do $$ begin
  create type public.app_role as enum ('admin','editor','viewer');
exception when duplicate_object then null; end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text not null default '',
  role public.app_role not null default 'viewer',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.companies (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id)
);

create table if not exists public.receipts (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete restrict,
  receipt_no bigint,
  receipt_date date,
  amount numeric(18,2),
  details text,
  created_by uuid references auth.users(id),
  updated_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists ux_receipts_company_no on public.receipts(company_id,receipt_no) where receipt_no is not null;
create index if not exists ix_receipts_date on public.receipts(receipt_date);

create schema if not exists private;
create or replace function private.current_app_role()
returns text language sql stable security definer set search_path=''
as $$ select role::text from public.profiles where id=(select auth.uid()) and active=true limit 1 $$;
revoke execute on function private.current_app_role() from public;
grant usage on schema private to authenticated;
grant execute on function private.current_app_role() to authenticated;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public
as $$
begin
  insert into public.profiles(id,email,display_name,role,active)
  values(new.id,new.email,coalesce(new.raw_user_meta_data->>'display_name',''),'viewer',true)
  on conflict(id) do nothing;
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

-- أنشئ profiles للمستخدمين الذين أُنشئوا قبل إضافة الـ trigger.
insert into public.profiles(id,email,display_name,role,active)
select id,email,coalesce(raw_user_meta_data->>'display_name',''),'viewer',true from auth.users
on conflict(id) do nothing;

alter table public.profiles enable row level security;
alter table public.companies enable row level security;
alter table public.receipts enable row level security;

revoke all on public.profiles,public.companies,public.receipts from anon,authenticated;
grant select on public.profiles to authenticated;
grant select,insert,update,delete on public.companies,public.receipts to authenticated;
grant usage,select on all sequences in schema public to authenticated;

-- إعادة إنشاء السياسات بصورة قابلة لإعادة تشغيل الملف.
drop policy if exists profile_read on public.profiles;
drop policy if exists profile_admin_update on public.profiles;
drop policy if exists companies_read on public.companies;
drop policy if exists companies_insert on public.companies;
drop policy if exists companies_update on public.companies;
drop policy if exists companies_delete on public.companies;
drop policy if exists receipts_read on public.receipts;
drop policy if exists receipts_insert on public.receipts;
drop policy if exists receipts_update on public.receipts;
drop policy if exists receipts_delete on public.receipts;

create policy profile_read on public.profiles for select to authenticated
using (id=(select auth.uid()) or (select private.current_app_role())='admin');
create policy profile_admin_update on public.profiles for update to authenticated
using ((select private.current_app_role())='admin')
with check ((select private.current_app_role())='admin');

create policy companies_read on public.companies for select to authenticated
using ((select private.current_app_role()) in ('admin','editor','viewer'));
create policy companies_insert on public.companies for insert to authenticated
with check ((select private.current_app_role()) in ('admin','editor'));
create policy companies_update on public.companies for update to authenticated
using ((select private.current_app_role()) in ('admin','editor'))
with check ((select private.current_app_role()) in ('admin','editor'));
create policy companies_delete on public.companies for delete to authenticated
using ((select private.current_app_role()) in ('admin','editor'));

create policy receipts_read on public.receipts for select to authenticated
using ((select private.current_app_role()) in ('admin','editor','viewer'));
create policy receipts_insert on public.receipts for insert to authenticated
with check ((select private.current_app_role()) in ('admin','editor'));
create policy receipts_update on public.receipts for update to authenticated
using ((select private.current_app_role()) in ('admin','editor'))
with check ((select private.current_app_role()) in ('admin','editor'));
create policy receipts_delete on public.receipts for delete to authenticated
using ((select private.current_app_role()) in ('admin','editor'));

